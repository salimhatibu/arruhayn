// A round control with its icon and a short label under it, as in Zoom and Meet. `on` marks a
// control that is currently active (a raised hand, a running share); `danger` is for leaving.
export function ControlButton({
  icon,
  label,
  onClick,
  on,
  off,
  danger,
  pressed,
}: {
  icon: LiveIconName
  label: string
  onClick: () => void
  on?: boolean
  off?: boolean
  danger?: boolean
  pressed?: boolean
}) {
  const kind = danger ? ' is-danger' : on ? ' is-on' : off ? ' is-off' : ''
  return (
    <button type="button" className={`ctl${kind}`} onClick={onClick} title={label} aria-label={label} aria-pressed={pressed}>
      <span className="ctl-icon">
        <LiveIcon name={icon} />
      </span>
      <span className="ctl-label">{label}</span>
    </button>
  )
}
